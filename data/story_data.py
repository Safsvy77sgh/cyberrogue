def get_lore_entry(lore_id):
    """Возвращает запись лора по ID."""
    for entry in LORE_ENTRIES:
        if entry["id"] == lore_id:
            return entry
    return None

def get_dialogue(dialogue_id):
    """Возвращает диалог по ID."""
    return DIALOGUES.get(dialogue_id)

def get_chapter(chapter_id):
    """Возвращает главу по ID."""
    for chapter in STORY_CHAPTERS:
        if chapter["id"] == chapter_id:
            return chapter
    return None

def get_character(character_id):
    """Возвращает персонажа по ID."""
    return CHARACTERS.get(character_id)

def get_ending(ending_id):
    """Возвращает концовку по ID."""
    for ending in ENDINGS:
        if ending["id"] == ending_id:
            return ending
    return None

def get_side_quest(quest_id):
    """Возвращает побочный квест по ID."""
    for quest in SIDE_QUESTS:
        if quest["id"] == quest_id:
            return quest
    return None

def check_flags_for_ending(flags, ending_id):
    """Проверяет, выполнены ли условия для концовки."""
    ending = get_ending(ending_id)
    if not ending:
        return False
    for condition in ending["conditions"]:
        if condition.startswith("not "):
            if flags.get(condition[4:], False):
                return False
        else:
            if not flags.get(condition, False):
                return False
    return True

def get_all_possible_endings(flags):
    """Возвращает список доступных концовок на основе флагов."""
    result = []
    for ending in ENDINGS:
        if check_flags_for_ending(flags, ending["id"]):
            result.append(ending["id"])
    return result

