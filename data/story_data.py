def check_endings(flags: dict) -> List[str]:
    """
    Возвращает список id концовок, условия которых выполнены.
    """
    unlocked = []
    for ending in ENDINGS:
        conditions_met = True
        for cond in ending["conditions"]:
            # Проверка на отрицание
            if cond.startswith("not "):
                flag_name = cond[4:]
                if flags.get(flag_name, False):
                    conditions_met = False
                    break
            else:
                if not flags.get(cond, False):
                    conditions_met = False
                    break
        if conditions_met:
            unlocked.append(ending["id"])
    return unlocked

def get_ending_by_id(ending_id: str) -> dict:
    """Возвращает концовку по id."""
    for ending in ENDINGS:
        if ending["id"] == ending_id:
            return ending
    return None

